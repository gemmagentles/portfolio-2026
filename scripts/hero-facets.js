// Regenerates the hero's V-shaped facet bands in partials/hero-facets.html:
//
//   node scripts/hero-facets.js
//
// Pointy-top hexagons (six triangles each) are tiled across a 1440-wide band and trimmed to a V that is shallow at the
// sides and deepest in the middle; the bottom band is the same, mirrored. Each triangle gets one of the 28 gradients
// from the V10 design, six in a row per hexagon. The gradients are read from the file's existing <defs>, so change
// colours there; change the hexagon size and the V's shape with the constants below.
import fs from 'node:fs';

const outFile = new URL('../partials/hero-facets.html', import.meta.url);

const W = 1440, H = 260; // band size in viewBox units
const R = 36; // hexagon radius (the design's were about 96)
const EDGE = 20, TIP = 255; // band depth at the sides and at the point in the middle
const GRADIENTS = 28;

const hexW = Math.sqrt(3) * R, rowH = 1.5 * R;
const vertex = (cx, cy, i) => {
  const a = ((-90 + 60 * i) * Math.PI) / 180;
  return [cx + R * Math.cos(a), cy + R * Math.sin(a)];
};
const f = (n) => Math.round(n); // whole units keep the file small; each outline covers any tiny gaps

// Depth of the V at x: straight lines from EDGE at the sides down to TIP in the middle.
const depth = (x) => EDGE + (TIP - EDGE) * (1 - Math.min(1, Math.abs(x - W / 2) / (W / 2)));

function band(flip) {
  const paths = [];
  let hex = flip ? 3 : 0; // start the bottom band on a different colour group
  for (let row = -1; row * rowH < H + R; row++) {
    const offset = row % 2 ? hexW / 2 : 0;
    for (let cx = -hexW + offset; cx < W + hexW; cx += hexW) {
      const cy = row * rowH;
      if (cy - R > depth(cx)) continue; // wholly outside the V (the clip path trims the rest to a clean edge)
      const y = (v) => (flip ? H - v : v);
      // Pop-in order: the sides first, the point in the middle last, so the V "draws" towards the text.
      const delay = 0.15 + 0.85 * (1 - Math.abs(cx - W / 2) / (W / 2)) + 0.05 * (cy / TIP);
      // One group per hexagon, carrying its pop-in delay; its six triangles inherit it.
      const triangles = [];
      for (let t = 0; t < 6; t++) {
        const [x1, y1] = vertex(cx, cy, t), [x2, y2] = vertex(cx, cy, t + 1);
        const g = (hex * 6 + t) % GRADIENTS;
        triangles.push(
          `<path d="M${f(cx)} ${f(y(cy))}L${f(x1)} ${f(y(y1))}L${f(x2)} ${f(y(y2))}Z" fill="url(#hf-g${g})" stroke="url(#hf-g${g})"/>`,
        );
      }
      paths.push(`<g style="--d:${delay.toFixed(2)}s">${triangles.join('')}</g>`);
      hex++;
    }
  }
  return paths;
}

const top = band(false), bottom = band(true);
const defs = fs.readFileSync(outFile, 'utf8').match(/<defs>[\s\S]*?<\/defs>/)[0];
const out = `<!--
  The hero's geometric facets: small hexagons (six triangles each) in the brand's pinks, purples, blues and black,
  in two bands that form a V pointing at the text. The top band hangs down to a point in the middle and the bottom
  band rises to one; each is trimmed to a clean V by a clip path. Each band is cropped to the screen's width.
  Each hexagon pops in after its --d delay, the sides first and the points last (styles in
  src/scss/pages/_home.scss). Purely decorative.
  Generated by a script (hexagon size, V depth and colours are set there), so regenerate rather than edit by hand.
-->
<svg class="hero__facets hero__facets--top" viewBox="0 0 ${W} ${H}" preserveAspectRatio="xMidYMin slice" aria-hidden="true" focusable="false">
${defs}
<clipPath id="hf-v-top"><polygon points="0,0 ${W},0 ${W},${EDGE} ${W / 2},${TIP} 0,${EDGE}"/></clipPath>
<g clip-path="url(#hf-v-top)">
${top.join('\n')}
</g>
</svg>
<svg class="hero__facets hero__facets--bottom" viewBox="0 0 ${W} ${H}" preserveAspectRatio="xMidYMax slice" aria-hidden="true" focusable="false">
<defs><clipPath id="hf-v-bottom"><polygon points="0,${H} ${W},${H} ${W},${H - EDGE} ${W / 2},${H - TIP} 0,${H - EDGE}"/></clipPath></defs>
<g clip-path="url(#hf-v-bottom)">
${bottom.join('\n')}
</g>
</svg>
`;
fs.writeFileSync(outFile, out);
console.log(`top ${top.length} hexagons, bottom ${bottom.length} hexagons, ${out.length} bytes`);
